@pytest.mark.parametrize(
    ("changed_entry", "replacement", "message"),
    [
        (None, None, None),
        ("echo", None, "initialise"),
        ("plan", Missing, "missing step"),
        ("echo", Configured, "constructor arguments"),
        ("echo", AsyncEcho, "must run synchronously"),
        ("echo", Unimplemented, "must implement run"),
        ("plan", BlankName, "Invalid checklist configuration"),
        ("plan", InvalidPolicy, "Invalid checklist configuration"),
    ],
)
def test_release_validates_classes_and_plans_before_update(
    changed_entry: str | None,
    replacement: vault.ContractClass | None,
    message: str | None,
    monkeypatch: pytest.MonkeyPatch,
) -> None:
    bundle, meta = _compile_fixture(monkeypatch, 4)
    files = {
        "previous.py": ARCHIVE.encode(),
        "candidate.py": "".join(vault._bundle_lines(bundle, meta)).encode(),
    }

    def open_bundle(
        path: str, *_args: object, **_kwargs: object
    ) -> io.BytesIO:
        return io.BytesIO(files[path])

    state = vault.SQLiteReleaseState("unused.db", "test", allow_initial=True)
    materialise = SecureRegistry._load_class
    loaded: list[str] = []

    def load_class(registry: SecureRegistry, name: str) -> vault.ContractClass:
        if registry.version == 4:
            loaded.append(name)
            if name == changed_entry:
                if replacement is None:
                    raise BundleError("fixture class could not initialise")
                return replacement
        return materialise(registry, name)

    monkeypatch.setattr(vault, "open", open_bundle, raising=False)
    monkeypatch.setattr(SecureRegistry, "_load_class", load_class)
    with closing(sqlite3.connect(":memory:")) as connection:

        class MemoryState:
            def accept(
                self,
                release: vault.ReleaseIdentity,
                *,
                prepare: Callable[[], None],
            ) -> None:
                with connection:
                    state._accept(connection, release, prepare=prepare)

        admission = MemoryState()
        vault.load_release_bundle("previous.py", FIXTURE_KEY, state=admission)
        if message is None:
            registry = vault.load_release_bundle(
                "candidate.py", FIXTURE_KEY, state=admission
            )
            assert loaded == ["echo", "plan"]
            assert ChecklistRunner(registry).run("plan").ok
            assert loaded == ["echo", "plan"]
            with pytest.raises(vault.ReleaseStateError, match="older"):
                vault.load_release_bundle(
                    "previous.py", FIXTURE_KEY, state=admission
                )
        else:
            with pytest.raises(BundleError, match=message):
                vault.load_release_bundle(
                    "candidate.py", FIXTURE_KEY, state=admission
                )
            registry = vault.load_release_bundle(
                "previous.py", FIXTURE_KEY, state=admission
            )
            assert registry.version == 3
            assert ChecklistRunner(registry).run(["connect"]).ok


