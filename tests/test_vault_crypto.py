def test_rfc_8452_known_answer(monkeypatch: pytest.MonkeyPatch) -> None:
    vector_key = bytes.fromhex("01000000000000000000000000000000")
    nonce = bytes.fromhex("030000000000000000000000")
    tag = bytes.fromhex("dc20e2d83f25705bb49e439eca56de25")

    def fixed_nonce(_size: int) -> bytes:
        return nonce

    monkeypatch.setattr(os, "urandom", fixed_nonce)
    assert crypto.encrypt(vector_key, b"", aad=b"") == nonce + tag
    assert crypto.decrypt(vector_key, nonce + tag, aad=b"") == b""


