@pytest.mark.parametrize("failure", [False, True])
def test_concurrent_requests_share_one_outcome(
    compiled: Fixture, monkeypatch: pytest.MonkeyPatch, failure: bool
) -> None:
    bundle, meta = compiled
    registry = SecureRegistry(bundle, FIXTURE_KEY, meta)
    materialise = registry._load_class
    ready = Event()
    waiter = Event()
    release = Event()
    calls: list[str] = []

    class Observed(Future[vault.ContractClass]):
        def result(self, timeout: float | None = None) -> vault.ContractClass:
            waiter.set()
            return super().result(timeout)

    def slow(name: str) -> vault.ContractClass:
        calls.append(name)
        ready.set()
        assert release.wait(2)
        if failure:
            raise BundleError("fixture worker failure")
        return materialise(name)

    monkeypatch.setattr(vault, "Future", Observed)
    monkeypatch.setattr(registry, "_load_class", slow)
    with ThreadPoolExecutor(2) as pool:
        first = pool.submit(registry.get, "echo")
        assert ready.wait(2)
        second = pool.submit(registry.get, "echo")
        try:
            assert waiter.wait(2)
        finally:
            release.set()
        if failure:
            for outcome in (first, second):
                with pytest.raises(
                    BundleError, match="fixture worker failure"
                ):
                    outcome.result(2)
        else:
            assert first.result(2) is second.result(2)
    assert calls == ["echo"]
    if failure:
        monkeypatch.setattr(registry, "_load_class", materialise)
        assert issubclass(registry.get("echo"), Step)


