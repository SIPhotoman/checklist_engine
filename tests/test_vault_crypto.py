@pytest.mark.parametrize("threaded", [False, True])
def test_expired_waiter_leaves_owner_running(
    compiled: Fixture, monkeypatch: pytest.MonkeyPatch, threaded: bool
) -> None:
    bundle, meta = compiled
    registry = SecureRegistry(bundle, FIXTURE_KEY, meta)
    materialise = registry._load_class
    entered = Event()
    finish = Event()

    def load(name: str) -> vault.ContractClass:
        entered.set()
        assert finish.wait(5)
        return materialise(name)

    monkeypatch.setattr(registry, "_load_class", load)
    plan = ["echo"]
    run = partial(
        ChecklistRunner(registry).run,
        plan,
        on_error=OnError(step_total_timeout=0.04),
    )
    with ThreadPoolExecutor(2) as pool:
        owner = pool.submit(registry.get, "echo")
        try:
            assert entered.wait(2)
            report = pool.submit(run).result(2) if threaded else run()
            assert report.results[0].error == "StepTimeout"
            assert report.results[0].attempts == 0
            assert not owner.done()
        finally:
            finish.set()
        assert owner.result(2) is registry.get("echo")
    assert not registry._pending


@pytest.mark.skipif(not hasattr(signal, "setitimer"), reason="Unix timer")
def test_alarm_during_registry_load_preserves_shared_result(
    compiled: Fixture, monkeypatch: pytest.MonkeyPatch
) -> None:
    alarm = signal.SIGALRM
    if signal.getsignal(alarm) != signal.SIG_DFL or any(
        signal.getitimer(signal.ITIMER_REAL)
    ):
        pytest.skip("The test host already owns SIGALRM")
    bundle, meta = compiled
    registry = SecureRegistry(bundle, FIXTURE_KEY, meta)
    materialise = registry._load_class
    now = 100.0

    def monotonic() -> float:
        return now

    def set_timer(*_args: object) -> tuple[float, float]:
        return (0.0, 0.0)

    def load(name: str) -> vault.ContractClass:
        nonlocal now
        now += 2.0
        handler = signal.getsignal(alarm)
        assert callable(handler)
        handler(alarm, None)
        return materialise(name)

    clock = SimpleNamespace(monotonic=monotonic, time=time.time)
    monkeypatch.setattr(contracts, "time", clock)
    monkeypatch.setattr(engine, "time", clock)
    monkeypatch.setattr(signal, "setitimer", set_timer)
    monkeypatch.setattr(registry, "_load_class", load)
    report = ChecklistRunner(registry).run(
        ["echo"], on_error=OnError(step_total_timeout=1.0)
    )
    assert report.results[0].error == "StepTimeout"
    assert report.results[0].attempts == 0
    assert "echo" in registry._cache
    assert not registry._pending
    assert not registry._loading_threads
    assert signal.getsignal(alarm) == signal.SIG_DFL
    assert issubclass(registry.get("echo"), Step)


